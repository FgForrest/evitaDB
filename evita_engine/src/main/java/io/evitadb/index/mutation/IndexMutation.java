package io.evitadb.index.mutation;

import io.evitadb.api.requestResponse.mutation.MutationContract;

/**
 * Engine-internal mutation that affects only index structures, never entity storage. Generated by
 * post-processing triggers (e.g., facet expression re-evaluation) and dispatched through a dedicated
 * path on `EntityCollection`.
 *
 * Unlike {@link io.evitadb.api.requestResponse.mutation.Mutation Mutation}, these mutations:
 *
 * - are never passed from outside the engine
 * - are never written to WAL (regenerated deterministically on replay)
 * - are processed entirely by the target `EntityCollection`
 *
 * This is a marker interface — concrete leaf mutations (e.g., {@link ReevaluateExpressionMutation})
 * carry domain-specific fields. The target entity type is NOT on this interface — it is carried by the
 * wrapping {@link EntityIndexMutation} transport envelope, which routes the mutations to the correct
 * `EntityCollection`.
 *
 * **Implementation constraint:** all implementations **must** be final classes or records. The
 * {@link IndexMutationExecutorRegistry} dispatches mutations using exact `Class` identity matching
 * via `Map.get(mutation.getClass())` — it does NOT traverse the class hierarchy. A non-final
 * implementation whose subclass is not separately registered would silently fail to dispatch.
 *
 * @author Jan Novotný (novotny@fg.cz), FG Forrest a.s. (c) 2026
 */
public interface IndexMutation extends MutationContract {
}
