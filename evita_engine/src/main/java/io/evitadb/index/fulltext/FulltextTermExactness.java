package io.evitadb.index.fulltext;

/** Best matching class of a dictionary term across a query word's expansion legs, in preference order. */
public enum FulltextTermExactness {
	/** The dictionary term is one of the query word's analyzed variants. */
	EXACT,
	/** The dictionary term starts with the unfinished fragment or one of its analyzed variants. */
	PREFIX,
	/** The dictionary term is reached through a finite or open-ended typo walk. */
	FUZZY
}
