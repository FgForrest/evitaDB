package io.evitadb.performance.externalApi.graphql.documentCache;

import io.evitadb.performance.setup.BenchmarkForkArgs;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Warmup;
import org.openjdk.jmh.infra.Blackhole;

import java.util.concurrent.TimeUnit;

/**
 * Measures the effect of the parsed document cache of the catalog data API: a static product detail page document
 * (with listing sections) executed in-process against an artificial catalog, with the cache disabled
 * (`documentCacheSizeInBytes = 0`) and enabled. HTTP transport and JSON (de)serialization are deliberately left out
 * so that the difference is not diluted by costs the cache does not touch.
 *
 * Run e.g. with `-prof gc` to see the saved allocations as well.
 *
 * @author Lukáš Hornych, FG Forrest a.s. (c) 2026
 */
@BenchmarkMode({Mode.AverageTime})
@OutputTimeUnit(TimeUnit.MICROSECONDS)
@Warmup(iterations = 3, time = 10, timeUnit = TimeUnit.SECONDS)
@Measurement(iterations = 5, time = 10, timeUnit = TimeUnit.SECONDS)
@Fork(
	value = 1,
	jvmArgsAppend = {
		BenchmarkForkArgs.ADD_OPENS, BenchmarkForkArgs.OPEN_LANG,
		BenchmarkForkArgs.ADD_OPENS, BenchmarkForkArgs.OPEN_LANG_INVOKE,
		BenchmarkForkArgs.ADD_OPENS, BenchmarkForkArgs.OPEN_MATH,
		BenchmarkForkArgs.ADD_OPENS, BenchmarkForkArgs.OPEN_UTIL
	}
)
public class GraphQLDocumentCacheBenchmark {

	/**
	 * Executes the static product detail page document with random variables.
	 */
	@Benchmark
	public void productDetailPage(GraphQLDocumentCacheBenchmarkState state, Blackhole blackhole) {
		blackhole.consume(state.execute());
	}
}
