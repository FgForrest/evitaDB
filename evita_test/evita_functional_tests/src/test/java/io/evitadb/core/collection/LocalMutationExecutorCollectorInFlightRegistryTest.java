import io.evitadb.core.catalog.Catalog;
import io.evitadb.index.mutation.ConsistencyCheckingLocalMutationExecutor.ImplicitMutationBehavior;
import io.evitadb.test.EvitaTestSupport;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.EnumSource;

import javax.annotation.Nonnull;
import java.util.EnumSet;
import java.util.function.Consumer;

import static io.evitadb.api.query.QueryConstraints.entityFetchAllContent;
import static io.evitadb.test.TestTags.ENGINE;
import static io.evitadb.test.TestTags.REFERENCE;
import static io.evitadb.test.TestTags.TRANSACTION;
import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Verifies the lifetime of the in-flight executor registry of {@link LocalMutationExecutorCollector}: the executors of
 * a root mutation and of the reflected mutations it spawns in another collection are registered while it runs, and
 * none of them survives the root mutation - whether it commits or fails and is rolled back - so no later mutation can
 * be served a part from an executor that is no longer in flight.
 *
 * The root mutations run through `EntityCollection#applyMutations` with a collector the test holds on to, exactly as
 * an upsert does, so the reflected mutations are generated by the engine itself. That the registry did hold the root
 * and the nested executors while the mutation ran is what makes the emptiness asserted afterwards meaningful: with the
 * clearing at the end of the root mutation removed, these tests find every one of them still registered. The reads
 * served by the registry while a root mutation is in flight are covered by `OtherOwnerReferenceRowVisibilityTest`.
 *
 * @author Jan Novotný (novotny@fg.cz), FG Forrest a.s. (c) 2026
 */
@DisplayName("In-flight executor registry of a root mutation")
@Tag(ENGINE)
@Tag(REFERENCE)
@Tag(TRANSACTION)
class LocalMutationExecutorCollectorInFlightRegistryTest implements EvitaTestSupport {
	private static final String ENTITY_PRODUCT = "product";
	private static final String ENTITY_CATEGORY = "category";
	/** Mandatory reference of the product - removing the last one fails the root mutation after its nested ones. */
	private static final String REF_CATEGORIES = "categories";
	/** Reflected counterpart on the category collection, maintained by nested mutations of the product's. */
	private static final String REF_PRODUCTS = "products";
	private static final int CATEGORY_PK = 7;
	private static final int SECOND_CATEGORY_PK = 8;
	private static final int PRODUCT_PK = 1;

	private TestPaths paths;
	private Evita evita;

	@BeforeEach
	void setUp() {
		this.paths = createTestPaths("LocalMutationExecutorCollectorInFlightRegistryTest");
		this.evita = new Evita(newTestEvitaConfigurationBuilder(this.paths).build());
		this.evita.defineCatalog(TEST_CATALOG);
	}

	@AfterEach
	void tearDown() {
		this.evita.close();
		cleanupTestPaths(this.paths);
	}

	/**
	 * The product joins a second category: the root mutation runs the product's executor and a nested one of the
	 * category collection inserting the reflected row. Once the root mutation has committed, neither is in flight.
	 *
	 * @param state catalog state the scenario runs in
	 */
	@ParameterizedTest(name = "{0}")
	@EnumSource(value = CatalogState.class, names = {"WARMING_UP", "ALIVE"})
	@DisplayName("forgets every executor once the root mutation commits")
	void shouldForgetEveryExecutorWhenRootMutationCommits(@Nonnull CatalogState state) {
		prepare(state);

		this.evita.updateCatalog(
			TEST_CATALOG,
			(Consumer<EvitaSessionContract>) session -> {
				final EntityMutation mutation = session.getEntity(ENTITY_PRODUCT, PRODUCT_PK, entityFetchAllContent())
					.orElseThrow()
					.openForWrite()
					.setReference(REF_CATEGORIES, SECOND_CATEGORY_PK)
					.toMutation()
					.orElseThrow();
				final LocalMutationExecutorCollector collector = applyAsRootMutation(session, mutation);

				assertTrue(
					session.getEntity(ENTITY_CATEGORY, SECOND_CATEGORY_PK, entityFetchAllContent())
						.orElseThrow()
						.getReference(REF_PRODUCTS, PRODUCT_PK)
						.isPresent(),
					"The root mutation spawned no nested mutation of the category, so the registry was never shared"
				);
				assertNothingInFlight(collector, SECOND_CATEGORY_PK);
			}
		);
	}

	/**
	 * The product leaves its only category: the root mutation runs the nested mutation removing the reflected row
	 * from the category, and then fails its own consistency check, because the reference is mandatory. The rollback
	 * reverts both, and neither executor stays in flight.
	 *
	 * @param state catalog state the scenario runs in
	 */
	@ParameterizedTest(name = "{0}")
	@EnumSource(value = CatalogState.class, names = {"WARMING_UP", "ALIVE"})
	@DisplayName("forgets every executor once the root mutation fails after its nested mutations")
	void shouldForgetEveryExecutorWhenRootMutationFails(@Nonnull CatalogState state) {
		prepare(state);

		this.evita.updateCatalog(
			TEST_CATALOG,
			(Consumer<EvitaSessionContract>) session -> {
				final EntityMutation mutation = session.getEntity(ENTITY_PRODUCT, PRODUCT_PK, entityFetchAllContent())
					.orElseThrow()
					.openForWrite()
					.removeReference(REF_CATEGORIES, CATEGORY_PK)
					.toMutation()
					.orElseThrow();
				final EntityCollection products = collection(ENTITY_PRODUCT);
				final LocalMutationExecutorCollector collector = products.createLocalMutationExecutorCollector();

				assertThrows(
					ReferenceCardinalityViolatedException.class,
					() -> applyAsRootMutation(products, collector, session, mutation)
				);

				final SealedEntity category = session.getEntity(ENTITY_CATEGORY, CATEGORY_PK, entityFetchAllContent())
					.orElseThrow();
				assertEquals(
					1, category.getReferences(REF_PRODUCTS).size(),
					"The failed root mutation was not rolled back"
				);
				assertNothingInFlight(collector, CATEGORY_PK);
			}
		);
	}

	/**
	 * Creates the schema and the baseline: categories {@link #CATEGORY_PK} and {@link #SECOND_CATEGORY_PK}, and the
	 * product referencing the first of them through a reference that must not be left empty.
	 *
	 * @param state target catalog state
	 */
	private void prepare(@Nonnull CatalogState state) {
		this.evita.updateCatalog(
			TEST_CATALOG,
			(Consumer<EvitaSessionContract>) session -> {
				session.defineEntitySchema(ENTITY_PRODUCT)
					.withoutGeneratedPrimaryKey()
					.withReferenceToEntity(
						REF_CATEGORIES, ENTITY_CATEGORY, Cardinality.ONE_OR_MORE,
						whichIs -> whichIs.indexedForFilteringAndPartitioning()
					)
					.updateVia(session);
				session.defineEntitySchema(ENTITY_CATEGORY)
					.withoutGeneratedPrimaryKey()
					.withReflectedReferenceToEntity(
						REF_PRODUCTS, ENTITY_PRODUCT, REF_CATEGORIES,
						whichIs -> whichIs.withCardinality(Cardinality.ZERO_OR_MORE)
					)
					.updateVia(session);

				session.createNewEntity(ENTITY_CATEGORY, CATEGORY_PK).upsertVia(session);
				session.createNewEntity(ENTITY_CATEGORY, SECOND_CATEGORY_PK).upsertVia(session);
				session.createNewEntity(ENTITY_PRODUCT, PRODUCT_PK)
					.setReference(REF_CATEGORIES, CATEGORY_PK)
					.upsertVia(session);

				if (state == CatalogState.ALIVE) {
					session.goLiveAndClose();
				}
			}
		);
	}

	/**
	 * Applies a product mutation as a root mutation with a fresh collector and returns that collector.
	 *
	 * @param session  the open read-write session
	 * @param mutation the product mutation
	 * @return the collector the root mutation ran with
	 */
	@Nonnull
	private LocalMutationExecutorCollector applyAsRootMutation(
		@Nonnull EvitaSessionContract session,
		@Nonnull EntityMutation mutation
	) {
		final EntityCollection products = collection(ENTITY_PRODUCT);
		final LocalMutationExecutorCollector collector = products.createLocalMutationExecutorCollector();
		applyAsRootMutation(products, collector, session, mutation);
		return collector;
	}

	/**
	 * Applies a product mutation as a root mutation with the given collector - the way an upsert of the entity does,
	 * with every implicit mutation generated.
	 *
	 * @param products  the product collection
	 * @param collector the collector of the root mutation
	 * @param session   the open read-write session
	 * @param mutation  the product mutation
	 */
	private static void applyAsRootMutation(
		@Nonnull EntityCollection products,
		@Nonnull LocalMutationExecutorCollector collector,
		@Nonnull EvitaSessionContract session,
		@Nonnull EntityMutation mutation
	) {
		products.applyMutations(
			session,
			mutation,
			true,
			true,
			null,
			EnumSet.allOf(ImplicitMutationBehavior.class),
			collector,
			Void.class
		);
	}

	/**
	 * Asserts that the collector finds no in-flight executor of the product, of the category its nested mutation
	 * touched, or of the category it did not.
	 *
	 * @param collector         the collector of a finished root mutation
	 * @param nestedCategoryPk  primary key of the category the nested mutation touched
	 */
	private static void assertNothingInFlight(
		@Nonnull LocalMutationExecutorCollector collector,
		int nestedCategoryPk
	) {
		final int untouchedCategoryPk = nestedCategoryPk == CATEGORY_PK ? SECOND_CATEGORY_PK : CATEGORY_PK;
		// independent checks, so each executor left behind is reported on its own
		assertAll(
			() -> assertNull(
				collector.findInFlightAccessor(ENTITY_PRODUCT, PRODUCT_PK),
				"The root entity's executor is still registered after the root mutation finished"
			),
			() -> assertNull(
				collector.findInFlightAccessor(ENTITY_CATEGORY, nestedCategoryPk),
				"The nested executor of another collection is still registered after the root mutation finished"
			),
			() -> assertNull(collector.findInFlightAccessor(ENTITY_CATEGORY, untouchedCategoryPk))
		);
	}

	/**
	 * Returns the collection of the given entity type in the catalog the current session works with.
	 *
	 * @param entityType the entity type
	 * @return the collection
	 */
	@Nonnull
	private EntityCollection collection(@Nonnull String entityType) {
		return ((Catalog) this.evita.getCatalogInstanceOrThrowException(TEST_CATALOG))
			.getCollectionForEntityInternal(entityType)
			.orElseThrow(() -> new AssertionError("The test catalog holds no `" + entityType + "` collection"));
	}

}
